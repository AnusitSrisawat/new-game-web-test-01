#!/usr/bin/env python3
"""Write src/player_sprites.js: picture sizes of every player part and mount (run after tools/player_parts_cutout.py).

Usage (repo root):  python3 tools/player_parts_cutout.py && python3 tools/player_manifest.py
"""
import glob, json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {'parts': {}, 'mounts': {}}
for f in sorted(glob.glob(os.path.join(ROOT, 'assets/sprites/player/parts/*.png'))):
    im = Image.open(f); out['parts'][os.path.basename(f)[:-4]] = {'w': im.width, 'h': im.height}
for f in sorted(glob.glob(os.path.join(ROOT, 'assets/sprites/mounts/*.png'))):
    im = Image.open(f); out['mounts'][os.path.basename(f)[:-4]] = {'w': im.width, 'h': im.height}
with open(os.path.join(ROOT, 'src/player_sprites.js'), 'w') as fh:
    fh.write('// Generated by tools/player_manifest.py - picture sizes of the player parts / mounts\n')
    fh.write('export const PLAYER_SPRITES = ' + json.dumps(out, indent=1) + ';\n')
print({k: len(v) for k, v in out.items()})
