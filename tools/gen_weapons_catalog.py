"""Builds src/weapons_catalog.js from the weapon tables in ITEMS_AND_WEAPONS.md (sections 2 and 4.x)."""
import re, json
lines = open('ITEMS_AND_WEAPONS.md', encoding='utf-8').read().split('\n')
sections = {'## 2.': 'sword', '### 4.1': 'staff', '### 4.2': 'bow', '### 4.3': 'spear', '### 4.4': 'gun', '### 4.5': 'book'}
ICON = {'sword': '🗡️', 'staff': '🪄', 'bow': '🏹', 'spear': '🔱', 'gun': '🔫', 'book': '📖'}
# swords that already exist in the game under another id (same picture), or have no picture yet
SKIP = {'wooden_sword','iron_broadsword','bone_cleaver','rune_claymore','titan_earthbreaker','dragon_scale_blade',
        'storm_thunder_edge','chaos_blade','phoenix_edge','chrono_timeblade'}
out, cur = [], None
for ln in lines:
    for k, t in sections.items():
        if ln.startswith(k): cur = t
    if ln.startswith('## 5.'): cur = None
    if not cur or not ln.startswith('|') or '`' not in ln: continue
    c = [x.strip() for x in ln.strip().strip('|').split('|')]
    idx = next(i for i, x in enumerate(c) if re.fullmatch(r'`[a-z0-9_]+`', x))
    wid = c[idx].strip('`')
    if wid in SKIP: continue
    lv = int(re.search(r'Lv\.\s*(\d+)', ' '.join(c[:idx])).group(1))
    name, stats, rest = c[idx + 1], c[idx + 2], c[idx + 3:]
    price = None
    if cur == 'sword':  # columns: id | name | stats | price | desc
        price, desc = int(rest[0].replace(',', '')), rest[1]
    else:
        desc = rest[0]
    atk = int(m.group(1)) if (m := re.search(r'ATK\s*\+(\d+)', stats)) else 0
    dfn = int(m.group(1)) if (m := re.search(r'(?<![A-Z-])DEF\s*\+(\d+)', stats)) else 0
    if price is None: price = atk * 5 + lv * 3 + 10
    extra = [s.strip() for s in stats.split(',') if not re.match(r'\s*M?ATK\s*\+|\s*DEF\s*\+', s)]
    if extra: desc += ' (' + ', '.join(extra) + ')'
    out.append(dict(id=wid, name=name, weaponType=cur, atk=atk, def_=dfn, reqLevel=lv, price=price, icon=ICON[cur], desc=desc))
js = ["// Generated by tools/gen_weapons_catalog.py from ITEMS_AND_WEAPONS.md - weapons for every type (sword/staff/bow/spear/gun/book).",
      "// Special effects in the description (CRIT, FIRE, ...) are flavour only for now; ATK/DEF are real.",
      "export const EXTRA_WEAPONS = ["]
for w in out:
    js.append("  [%s, %s, '%s', %d, %d, %d, %d, %s, %s]," % (json.dumps(w['id']), json.dumps(w['name'], ensure_ascii=False), w['weaponType'], w['atk'], w['def_'], w['reqLevel'], w['price'], json.dumps(w['icon'], ensure_ascii=False), json.dumps(w['desc'], ensure_ascii=False)))
js += ["];", "",
"// Adds them to ITEMS (never replaces an item that already exists)",
"export function installWeapons(ITEMS) {",
"  for (const [id, name, weaponType, atk, def, reqLevel, price, icon, desc] of EXTRA_WEAPONS) {",
"    if (!ITEMS[id]) ITEMS[id] = { id, name, type: 'weapon', weaponType, atk, def, reqLevel, price, icon, desc };",
"  }", "}", ""]
open('src/weapons_catalog.js', 'w', encoding='utf-8').write('\n'.join(js))
from collections import Counter
print(len(out), Counter(w['weaponType'] for w in out))
