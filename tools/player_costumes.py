#!/usr/bin/env python3
"""Build the full-costume pictures (body + outfit + hat + wings baked together) from the cut parts.

Needs assets/sprites/player/base_body.png (tools/cut_base_body.py) and tools/player_parts_cutout.py output.
Output: assets/sprites/player/costume_<id>.png (+ src/player_sprites.js with sizes / anchors / mount data)

Usage (repo root):  python3 tools/player_parts_cutout.py && python3 tools/player_costumes.py
"""
import json, os
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, 'assets/sprites/player')
body = Image.open(os.path.join(P, 'base_body.png')).convert('RGBA')   # 135 x 301: head 0-130, neck ~135-145, feet at 300
part = lambda n: Image.open(os.path.join(P, 'parts', n + '.png')).convert('RGBA')
CW, CH = 520, 560
BX, BY = 190, 150                      # where the body goes on the canvas
HEAD_CX, TORSO_CX = 66, 65             # body-picture x of head / torso centre

def fit_w(im, w): return im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
def fit_h(im, h): return im.resize((round(im.width * h / im.height), h), Image.LANCZOS)

# hat id -> (width, bottom y relative to the body picture)
HATS = {'hat_helm': (150, 128), 'hat_wizard': (200, 70), 'hat_cat': (135, 52), 'hat_crown': (105, 36)}
# wings id -> (width, centre y relative to the body picture)
WINGS = {'wings_angel': (225, 165), 'wings_dragon': (270, 150), 'wings_fairy': (200, 160), 'cape_red': (150, 215)}

COSTUMES = {  # id: (outfit, hat, back)
  'knight':    ('outfit_knight',   'hat_helm',   'cape_red'),
  'ranger':    ('outfit_ranger',   'hat_cat',    'wings_fairy'),
  'sorcerer':  ('outfit_sorcerer', 'hat_wizard', None),
  'assassin':  ('outfit_assassin', None,         'wings_dragon'),
  'royal':     ('outfit_knight',   'hat_crown',  'wings_angel'),
}

def build(outfit, hat, back):
    c = Image.new('RGBA', (CW, CH), (0, 0, 0, 0))
    if back:
        w, cy = WINGS[back]; im = fit_w(part(back), w)
        c.alpha_composite(im, (BX + TORSO_CX - im.width // 2, BY + cy - im.height // 2))
    c.alpha_composite(body, (BX, BY))
    if outfit:
        im = fit_h(part(outfit), 172)
        c.alpha_composite(im, (BX + TORSO_CX - im.width // 2, BY + 301 - im.height + 2))
    if hat:
        w, bottom = HATS[hat]; im = fit_w(part(hat), w)
        c.alpha_composite(im, (BX + HEAD_CX - im.width // 2, BY + bottom - im.height))
    bbox = c.getbbox()
    return c.crop(bbox), (BX + TORSO_CX - bbox[0], BY + 301 - bbox[1])   # feet-centre anchor inside the trimmed image

def main():
    manifest = {'costumes': {}, 'shields': {}, 'mounts': {}}
    for cid, (o, h, b) in COSTUMES.items():
        im, anchor = build(o, h, b)
        im.save(os.path.join(P, f'costume_{cid}.png'))
        manifest['costumes'][cid] = {'w': im.width, 'h': im.height, 'fx': anchor[0], 'fy': anchor[1]}
    im, anchor = build(None, None, None)
    im.save(os.path.join(P, 'costume_none.png'))
    manifest['costumes']['none'] = {'w': im.width, 'h': im.height, 'fx': anchor[0], 'fy': anchor[1]}
    manifest['bodyHeight'] = 301
    for sid in ('shield_lion', 'shield_rune'):
        im = part(sid); manifest['shields'][sid] = {'w': im.width, 'h': im.height}
    M = os.path.join(ROOT, 'assets/sprites/mounts')
    for mid in ('mount_runner', 'mount_wolf', 'mount_unicorn', 'mount_drake'):
        im = Image.open(os.path.join(M, mid + '.png')); manifest['mounts'][mid] = {'w': im.width, 'h': im.height}
    with open(os.path.join(ROOT, 'src/player_sprites.js'), 'w') as f:
        f.write('// Generated by tools/player_costumes.py - sizes / anchors of the player + mount pictures\n')
        f.write('export const PLAYER_SPRITES = ' + json.dumps(manifest, indent=2) + ';\n')
    print(json.dumps(manifest))

if __name__ == '__main__':
    main()
