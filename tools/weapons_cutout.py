#!/usr/bin/env python3
"""Cut the sword pictures out of assets/weapons/weapons_tier{1,2}.jpg into upright transparent PNGs
(tip up, hilt at the bottom) in assets/sprites/weapons/<name>.png and write src/weapon_sprites.js.

Usage (repo root):  python3 tools/weapons_cutout.py
"""
import json, os, sys
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cutout import cutout, ROOT

# name -> (sheet, (x, y, w, h)) ; rectangles skip the printed caption under each sword
SWORDS = {
  'wooden_sword':     ('tier1', (90, 30, 230, 185)),
  'iron_broadsword':  ('tier1', (420, 30, 250, 185)),
  'steel_blade':      ('tier1', (720, 30, 260, 185)),
  'wolf_fang_saber':  ('tier1', (100, 270, 260, 170)),
  'bandit_cutlass':   ('tier1', (420, 270, 230, 170)),
  'knight_longsword': ('tier1', (90, 510, 240, 185)),
  'bone_cleaver':     ('tier1', (400, 505, 250, 190)),
  'rune_claymore':    ('tier1', (700, 550, 300, 390)),
  'shadow_dagger':    ('tier1', (100, 745, 230, 185)),
  'crimson_falchion': ('tier1', (400, 745, 250, 185)),
  'glacial_frostbrand': ('tier2', (90, 30, 250, 190)),
  'titan_earthbreaker': ('tier2', (740, 30, 270, 190)),
  'holy_excalibur':   ('tier2', (740, 270, 270, 190)),
  'dragon_scale_blade': ('tier2', (90, 510, 260, 190)),
  'astral_cosmic_saber': ('tier2', (420, 510, 250, 190)),
  'genesis_godslayer': ('tier2', (730, 750, 280, 190)),
}
SCALE = 0.5

def upright(img):
    a = np.asarray(img)[:, :, 3] > 100
    ys, xs = np.nonzero(a)
    pts = np.stack([xs, ys], 1).astype(float)
    c = pts.mean(0)
    u, s, vt = np.linalg.svd(pts - c, full_matrices=False)
    ax = vt[0]
    if ax[1] > 0: ax = -ax            # point the axis up (tip side) on screen
    ang = np.degrees(np.arctan2(ax[0], -ax[1]))   # clockwise degrees from straight up
    img = img.rotate(ang, resample=Image.BICUBIC, expand=True)   # PIL rotates counter-clockwise
    return img.crop(img.getbbox())

def main():
    sheets = {k: Image.open(os.path.join(ROOT, f'assets/weapons/weapons_{k}.jpg')).convert('RGB') for k in ('tier1', 'tier2')}
    out_dir = os.path.join(ROOT, 'assets/sprites/weapons')
    os.makedirs(out_dir, exist_ok=True)
    meta = {}
    for name, (sheet, (x, y, w, h)) in SWORDS.items():
        res = upright(cutout(sheets[sheet].crop((x, y, x + w, y + h)), (w, h)))
        res = res.resize((max(1, round(res.width * SCALE)), max(1, round(res.height * SCALE))), Image.LANCZOS)
        res.save(os.path.join(out_dir, name + '.png'), optimize=True)
        meta[name] = [res.width, res.height]
    js = ('// Generated by tools/weapons_cutout.py - upright sword pictures [width, height] (tip up, hilt at the bottom)\n'
          'export const WEAPON_SPRITES = ' + json.dumps(meta, indent=2) + ';\n')
    open(os.path.join(ROOT, 'src/weapon_sprites.js'), 'w').write(js)
    print('wrote', len(meta))

main()
