#!/usr/bin/env python3
"""Cut the armor parts out of assets/weapons/arrmor/arrmor-default.jpg into transparent PNGs
(assets/sprites/armor/<part>.png) and write src/armor_sprites.js ([width, height] of each part).

Usage (repo root):  python3 tools/armor_cutout.py
"""
import json, os, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from PIL import ImageFilter
from cutout import border_connected, ROOT

# part -> (x, y, w, h) on the 2048x2048 sheet; rectangles skip the printed captions
PARTS = {
  'helmet': (820, 60, 410, 390),
  'chest':  (730, 540, 600, 730),
  'arm_l':  (255, 530, 310, 650),
  'arm_r':  (1495, 570, 310, 610),
  'legs':   (775, 1385, 510, 520),
}
SCALE = 0.3
BG_TOL = 40    # silver armor is close to the grey background, so no 'enclosed hole' removal here

def keep_big(fg, frac=0.08):
    """Drop connected foreground parts smaller than `frac` of the biggest one."""
    h, w = fg.shape
    seen = np.zeros_like(fg)
    comps = []
    for y0, x0 in zip(*np.nonzero(fg)):
        if seen[y0, x0]:
            continue
        stack, pts = [(y0, x0)], []
        seen[y0, x0] = True
        while stack:
            y, x = stack.pop(); pts.append((y, x))
            for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                ny, nx = y + dy, x + dx
                if 0 <= ny < h and 0 <= nx < w and fg[ny, nx] and not seen[ny, nx]:
                    seen[ny, nx] = True; stack.append((ny, nx))
        comps.append(pts)
    big = max(len(c) for c in comps)
    out = np.zeros_like(fg)
    for c in comps:
        if len(c) > frac * big:
            ys, xs = zip(*c); out[ys, xs] = True
    return out

def cutout(img, out_size):
    rgb = np.asarray(img.convert('RGB')).astype(np.int32)
    border = np.concatenate([rgb[0], rgb[-1], rgb[:, 0], rgb[:, -1]])
    bg = np.median(border, axis=0)
    dist = np.sqrt(((rgb - bg) ** 2).sum(axis=2))
    fg = ~border_connected(dist < BG_TOL)
    # keep the big parts only (drops the glow sparkles and the printed captions)
    fg = keep_big(fg)
    m = Image.fromarray((fg * 255).astype(np.uint8)).filter(ImageFilter.MinFilter(5)).filter(ImageFilter.GaussianBlur(1.2))
    res = Image.fromarray(np.dstack([rgb.astype(np.uint8), np.asarray(m)]), 'RGBA')
    return res.resize(out_size, Image.LANCZOS)

def main():
    sheet = Image.open(os.path.join(ROOT, 'assets/weapons/arrmor/arrmor-default.jpg')).convert('RGB')
    out_dir = os.path.join(ROOT, 'assets/sprites/armor')
    os.makedirs(out_dir, exist_ok=True)
    meta = {}
    for name, (x, y, w, h) in PARTS.items():
        res = cutout(sheet.crop((x, y, x + w, y + h)), (w, h))
        res = res.crop(res.getbbox())
        if name == 'legs':   # two greaves side by side: save them as separate pictures so each leg can stride
            col = (np.asarray(res)[:, :, 3] > 40).any(axis=0)
            mid = res.width // 2
            gap = min((x for x in range(res.width // 3, 2 * res.width // 3) if not col[x]), key=lambda x: abs(x - mid), default=mid)
            for part, box in (('leg_l', (0, 0, gap, res.height)), ('leg_r', (gap, 0, res.width, res.height))):
                piece = res.crop(box); piece = piece.crop(piece.getbbox())
                piece = piece.resize((max(1, round(piece.width * SCALE)), max(1, round(piece.height * SCALE))), Image.LANCZOS)
                piece.save(os.path.join(out_dir, part + '.png'), optimize=True)
                meta[part] = [piece.width, piece.height]
            continue
        res = res.resize((max(1, round(res.width * SCALE)), max(1, round(res.height * SCALE))), Image.LANCZOS)
        res.save(os.path.join(out_dir, name + '.png'), optimize=True)
        meta[name] = [res.width, res.height]
    js = ('// Generated by tools/armor_cutout.py - armor part pictures [width, height]\n'
          'export const ARMOR_SPRITES = ' + json.dumps(meta, indent=2) + ';\n')
    open(os.path.join(ROOT, 'src/armor_sprites.js'), 'w').write(js)
    print(meta)

if __name__ == '__main__':
    main()
